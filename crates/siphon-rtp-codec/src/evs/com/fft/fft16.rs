//! `fft16`: the 16-point complex FFT kernel of TS 26.442 `lib_com/fft.c`, translated statement for
//! statement from the preprocessed reference (the `WORD322WORD16` constants folded).

use super::ComplexBuffer;
use crate::evs::basop::mpy_32_16_1;
use crate::itu::basic_ops::{l_add, l_shr, l_sub};

/// The first radix-4 stage of [`fft16`], scaled by `SCALEFACTOR16` when `b_scale != 0`, into `y`.
fn fft16_first_stage<C: ComplexBuffer + ?Sized>(
    c: &mut C,
    s: usize,
    b_scale: i16,
    y: &mut [i32; 32],
) {
    let mut x0: i32;
    let mut x1: i32;
    let mut x2: i32;
    let mut x3: i32;
    let mut x4: i32;
    let mut x5: i32;
    let mut x6: i32;
    let mut x7: i32;
    let mut t0: i32;
    let mut t2: i32;
    let mut t1: i32;
    let mut t3: i32;
    let mut t4: i32;
    let mut t7: i32;
    let mut t5: i32;
    let mut t6: i32;
    if b_scale != 0 {
        x0 = l_shr(c.re(0), 5);
        x1 = l_shr(c.im(0), 5);
        x2 = l_shr(c.re(s * 4), 5);
        x3 = l_shr(c.im(s * 4), 5);
        x4 = l_shr(c.re(s * 8), 5);
        x5 = l_shr(c.im(s * 8), 5);
        x6 = l_shr(c.re(s * 12), 5);
        x7 = l_shr(c.im(s * 12), 5);
        t0 = l_add(x0, x4);
        t2 = l_sub(x0, x4);
        t1 = l_add(x1, x5);
        t3 = l_sub(x1, x5);
        t4 = l_add(x2, x6);
        t7 = l_sub(x2, x6);
        t5 = l_add(x7, x3);
        t6 = l_sub(x7, x3);
        y[0] = l_add(t0, t4);
        y[1] = l_add(t1, t5);
        y[2] = l_sub(t2, t6);
        y[3] = l_sub(t3, t7);
        y[4] = l_sub(t0, t4);
        y[5] = l_sub(t1, t5);
        y[6] = l_add(t2, t6);
        y[7] = l_add(t3, t7);
        x0 = l_shr(c.re(s), 5);
        x1 = l_shr(c.im(s), 5);
        x2 = l_shr(c.re(s * 5), 5);
        x3 = l_shr(c.im(s * 5), 5);
        x4 = l_shr(c.re(s * 9), 5);
        x5 = l_shr(c.im(s * 9), 5);
        x6 = l_shr(c.re(s * 13), 5);
        x7 = l_shr(c.im(s * 13), 5);
        t0 = l_add(x0, x4);
        t2 = l_sub(x0, x4);
        t1 = l_add(x1, x5);
        t3 = l_sub(x1, x5);
        t4 = l_add(x2, x6);
        t7 = l_sub(x2, x6);
        t5 = l_add(x7, x3);
        t6 = l_sub(x7, x3);
        y[8] = l_add(t0, t4);
        y[9] = l_add(t1, t5);
        y[10] = l_sub(t2, t6);
        y[11] = l_sub(t3, t7);
        y[12] = l_sub(t0, t4);
        y[13] = l_sub(t1, t5);
        y[14] = l_add(t2, t6);
        y[15] = l_add(t3, t7);
        x0 = l_shr(c.re(s * 2), 5);
        x1 = l_shr(c.im(s * 2), 5);
        x2 = l_shr(c.re(s * 6), 5);
        x3 = l_shr(c.im(s * 6), 5);
        x4 = l_shr(c.re(s * 10), 5);
        x5 = l_shr(c.im(s * 10), 5);
        x6 = l_shr(c.re(s * 14), 5);
        x7 = l_shr(c.im(s * 14), 5);
        t0 = l_add(x0, x4);
        t2 = l_sub(x0, x4);
        t1 = l_add(x1, x5);
        t3 = l_sub(x1, x5);
        t4 = l_add(x2, x6);
        t7 = l_sub(x2, x6);
        t5 = l_add(x7, x3);
        t6 = l_sub(x7, x3);
        y[16] = l_add(t0, t4);
        y[17] = l_add(t1, t5);
        y[18] = l_sub(t2, t6);
        y[19] = l_sub(t3, t7);
        y[20] = l_sub(t1, t5);
        y[21] = l_sub(t4, t0);
        y[22] = l_add(t2, t6);
        y[23] = l_add(t3, t7);
        x0 = l_shr(c.re(s * 3), 5);
        x1 = l_shr(c.im(s * 3), 5);
        x2 = l_shr(c.re(s * 7), 5);
        x3 = l_shr(c.im(s * 7), 5);
        x4 = l_shr(c.re(s * 11), 5);
        x5 = l_shr(c.im(s * 11), 5);
        x6 = l_shr(c.re(s * 15), 5);
        x7 = l_shr(c.im(s * 15), 5);
        t0 = l_add(x0, x4);
        t2 = l_sub(x0, x4);
        t1 = l_add(x1, x5);
        t3 = l_sub(x1, x5);
        t4 = l_add(x2, x6);
        t7 = l_sub(x2, x6);
        t5 = l_add(x7, x3);
        t6 = l_sub(x7, x3);
        y[24] = l_add(t0, t4);
        y[25] = l_add(t1, t5);
        y[26] = l_sub(t2, t6);
        y[27] = l_sub(t3, t7);
        y[28] = l_sub(t0, t4);
        y[29] = l_sub(t1, t5);
        y[30] = l_add(t2, t6);
        y[31] = l_add(t3, t7);
    } else {
        t0 = l_add(c.re(0), c.re(s * 8));
        t2 = l_sub(c.re(0), c.re(s * 8));
        t1 = l_add(c.im(0), c.im(s * 8));
        t3 = l_sub(c.im(0), c.im(s * 8));
        t4 = l_add(c.re(s * 4), c.re(s * 12));
        t7 = l_sub(c.re(s * 4), c.re(s * 12));
        t5 = l_add(c.im(s * 12), c.im(s * 4));
        t6 = l_sub(c.im(s * 12), c.im(s * 4));
        y[0] = l_add(t0, t4);
        y[1] = l_add(t1, t5);
        y[2] = l_sub(t2, t6);
        y[3] = l_sub(t3, t7);
        y[4] = l_sub(t0, t4);
        y[5] = l_sub(t1, t5);
        y[6] = l_add(t2, t6);
        y[7] = l_add(t3, t7);
        t0 = l_add(c.re(s), c.re(s * 9));
        t2 = l_sub(c.re(s), c.re(s * 9));
        t1 = l_add(c.im(s), c.im(s * 9));
        t3 = l_sub(c.im(s), c.im(s * 9));
        t4 = l_add(c.re(s * 5), c.re(s * 13));
        t7 = l_sub(c.re(s * 5), c.re(s * 13));
        t5 = l_add(c.im(s * 13), c.im(s * 5));
        t6 = l_sub(c.im(s * 13), c.im(s * 5));
        y[8] = l_add(t0, t4);
        y[9] = l_add(t1, t5);
        y[10] = l_sub(t2, t6);
        y[11] = l_sub(t3, t7);
        y[12] = l_sub(t0, t4);
        y[13] = l_sub(t1, t5);
        y[14] = l_add(t2, t6);
        y[15] = l_add(t3, t7);
        t0 = l_add(c.re(s * 2), c.re(s * 10));
        t2 = l_sub(c.re(s * 2), c.re(s * 10));
        t1 = l_add(c.im(s * 2), c.im(s * 10));
        t3 = l_sub(c.im(s * 2), c.im(s * 10));
        t4 = l_add(c.re(s * 6), c.re(s * 14));
        t7 = l_sub(c.re(s * 6), c.re(s * 14));
        t5 = l_add(c.im(s * 14), c.im(s * 6));
        t6 = l_sub(c.im(s * 14), c.im(s * 6));
        y[16] = l_add(t0, t4);
        y[17] = l_add(t1, t5);
        y[18] = l_sub(t2, t6);
        y[19] = l_sub(t3, t7);
        y[20] = l_sub(t1, t5);
        y[21] = l_sub(t4, t0);
        y[22] = l_add(t2, t6);
        y[23] = l_add(t3, t7);
        t0 = l_add(c.re(s * 3), c.re(s * 11));
        t2 = l_sub(c.re(s * 3), c.re(s * 11));
        t1 = l_add(c.im(s * 3), c.im(s * 11));
        t3 = l_sub(c.im(s * 3), c.im(s * 11));
        t4 = l_add(c.re(s * 7), c.re(s * 15));
        t7 = l_sub(c.re(s * 7), c.re(s * 15));
        t5 = l_add(c.im(s * 15), c.im(s * 7));
        t6 = l_sub(c.im(s * 15), c.im(s * 7));
        y[24] = l_add(t0, t4);
        y[25] = l_add(t1, t5);
        y[26] = l_sub(t2, t6);
        y[27] = l_sub(t3, t7);
        y[28] = l_sub(t0, t4);
        y[29] = l_sub(t1, t5);
        y[30] = l_add(t2, t6);
        y[31] = l_add(t3, t7);
    }
}

/// `fft16`: in-place 16-point FFT of `c` at stride `s`; `b_scale != 0` scales the input down by
/// `SCALEFACTOR16` first (the reference's public kernel, also called by `lpc_tools_fx.c`).
pub fn fft16<C: ComplexBuffer + ?Sized>(c: &mut C, s: usize, b_scale: i16) {
    let mut y = [0i32; 32];
    fft16_first_stage(c, s, b_scale, &mut y);
    let mut x0 = mpy_32_16_1(y[22], -23170);
    let mut x1 = mpy_32_16_1(y[23], -23170);
    y[22] = l_sub(x0, x1);
    y[23] = l_add(x0, x1);
    x0 = mpy_32_16_1(y[28], -23170);
    x1 = mpy_32_16_1(y[29], -23170);
    y[28] = l_sub(x0, x1);
    y[29] = l_add(x0, x1);
    x0 = mpy_32_16_1(y[12], 23170);
    x1 = mpy_32_16_1(y[13], 23170);
    y[12] = l_add(x0, x1);
    y[13] = l_sub(x1, x0);
    x0 = mpy_32_16_1(y[18], 23170);
    x1 = mpy_32_16_1(y[19], 23170);
    y[18] = l_add(x0, x1);
    y[19] = l_sub(x1, x0);
    x0 = mpy_32_16_1(y[10], 30274);
    x1 = mpy_32_16_1(y[11], -12540);
    let mut x2 = mpy_32_16_1(y[10], -12540);
    let mut x3 = mpy_32_16_1(y[11], 30274);
    y[10] = l_sub(x0, x1);
    y[11] = l_add(x2, x3);
    x0 = mpy_32_16_1(y[14], 12540);
    x1 = mpy_32_16_1(y[15], -30274);
    x2 = mpy_32_16_1(y[14], -30274);
    x3 = mpy_32_16_1(y[15], 12540);
    y[14] = l_sub(x0, x1);
    y[15] = l_add(x2, x3);
    x0 = mpy_32_16_1(y[26], 12540);
    x1 = mpy_32_16_1(y[27], -30274);
    x2 = mpy_32_16_1(y[26], -30274);
    x3 = mpy_32_16_1(y[27], 12540);
    y[26] = l_sub(x0, x1);
    y[27] = l_add(x2, x3);
    x0 = mpy_32_16_1(y[30], -30274);
    x1 = mpy_32_16_1(y[31], 12540);
    x2 = mpy_32_16_1(y[30], 12540);
    x3 = mpy_32_16_1(y[31], -30274);
    y[30] = l_sub(x0, x1);
    y[31] = l_add(x2, x3);
    let mut t0 = l_add(y[0], y[16]);
    let mut t2 = l_sub(y[0], y[16]);
    let mut t1 = l_add(y[1], y[17]);
    let mut t3 = l_sub(y[1], y[17]);
    let mut t4 = l_add(y[8], y[24]);
    let mut t7 = l_sub(y[8], y[24]);
    let mut t5 = l_add(y[25], y[9]);
    let mut t6 = l_sub(y[25], y[9]);
    c.set_re(0, l_add(t0, t4));
    c.set_im(0, l_add(t1, t5));
    c.set_re(s * 4, l_sub(t2, t6));
    c.set_im(s * 4, l_sub(t3, t7));
    c.set_re(s * 8, l_sub(t0, t4));
    c.set_im(s * 8, l_sub(t1, t5));
    c.set_re(s * 12, l_add(t2, t6));
    c.set_im(s * 12, l_add(t3, t7));
    t0 = l_add(y[2], y[18]);
    t2 = l_sub(y[2], y[18]);
    t1 = l_add(y[3], y[19]);
    t3 = l_sub(y[3], y[19]);
    t4 = l_add(y[10], y[26]);
    t7 = l_sub(y[10], y[26]);
    t5 = l_add(y[27], y[11]);
    t6 = l_sub(y[27], y[11]);
    c.set_re(s, l_add(t0, t4));
    c.set_im(s, l_add(t1, t5));
    c.set_re(s * 5, l_sub(t2, t6));
    c.set_im(s * 5, l_sub(t3, t7));
    c.set_re(s * 9, l_sub(t0, t4));
    c.set_im(s * 9, l_sub(t1, t5));
    c.set_re(s * 13, l_add(t2, t6));
    c.set_im(s * 13, l_add(t3, t7));
    t0 = l_add(y[4], y[20]);
    t2 = l_sub(y[4], y[20]);
    t1 = l_add(y[5], y[21]);
    t3 = l_sub(y[5], y[21]);
    t4 = l_add(y[12], y[28]);
    t7 = l_sub(y[12], y[28]);
    t5 = l_add(y[29], y[13]);
    t6 = l_sub(y[29], y[13]);
    c.set_re(s * 2, l_add(t0, t4));
    c.set_im(s * 2, l_add(t1, t5));
    c.set_re(s * 6, l_sub(t2, t6));
    c.set_im(s * 6, l_sub(t3, t7));
    c.set_re(s * 10, l_sub(t0, t4));
    c.set_im(s * 10, l_sub(t1, t5));
    c.set_re(s * 14, l_add(t2, t6));
    c.set_im(s * 14, l_add(t3, t7));
    t0 = l_add(y[6], y[22]);
    t2 = l_sub(y[6], y[22]);
    t1 = l_add(y[7], y[23]);
    t3 = l_sub(y[7], y[23]);
    t4 = l_add(y[14], y[30]);
    t7 = l_sub(y[14], y[30]);
    t5 = l_add(y[31], y[15]);
    t6 = l_sub(y[31], y[15]);
    c.set_re(s * 3, l_add(t0, t4));
    c.set_im(s * 3, l_add(t1, t5));
    c.set_re(s * 7, l_sub(t2, t6));
    c.set_im(s * 7, l_sub(t3, t7));
    c.set_re(s * 11, l_sub(t0, t4));
    c.set_im(s * 11, l_sub(t1, t5));
    c.set_re(s * 15, l_add(t2, t6));
    c.set_im(s * 15, l_add(t3, t7));
}
