    /// The whitening filter is the exact inverse of the synthesis recursion: feed it a signal
    /// generated by the same AR coefficients and everything past the first `order` samples is zero.
    #[test]
    fn lpc_analysis_filter_whitens_its_own_ar_process() {
        let coefficients = [0.6f32, -0.2, 0.1];
        let mut signal = [0.0f32; 32];
        signal[0] = 1.0;
        signal[1] = -0.5;
        signal[2] = 0.25;
        for index in 3..32 {
            signal[index] = signal[index - 1] * coefficients[0]
                + signal[index - 2] * coefficients[1]
                + signal[index - 3] * coefficients[2];
        }
        let mut residual = [1.0f32; 32];
        lpc_analysis_filter(&mut residual, &coefficients, &signal, 32);
        assert_eq!(
            &residual[..3],
            &[0.0, 0.0, 0.0],
            "first Order samples are zeroed"
        );
        for (index, &value) in residual.iter().enumerate().skip(3) {
            assert!(value.abs() < 1e-5, "sample {index} = {value}");
        }
    }

