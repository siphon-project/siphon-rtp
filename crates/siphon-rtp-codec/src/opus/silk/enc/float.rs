    proptest! {
        /// Both accumulators must agree with a straightforward `f64` sum to within the rounding
        /// slack of reordering ~256 terms.
        #[test]
        fn energy_agrees_with_a_naive_sum(values in prop::collection::vec(-1000.0f32..1000.0, 0..256)) {
            let naive: f64 = values.iter().map(|&v| f64::from(v) * f64::from(v)).sum();
            let computed = energy(&values);
            prop_assert!((computed - naive).abs() <= naive * 1e-12 + 1e-9);
        }

        /// Bandwidth expansion can only shrink a coefficient's magnitude for a chirp in (0, 1].
        #[test]
        fn bwexpander_never_grows_a_coefficient(
            values in prop::collection::vec(-4.0f32..4.0, 1..24),
            chirp in 0.01f32..=1.0,
        ) {
            let original = values.clone();
            let mut expanded = values;
            bwexpander(&mut expanded, chirp);
            for (index, (&before, &after)) in original.iter().zip(expanded.iter()).enumerate() {
                prop_assert!(
                    after.abs() <= before.abs() + 1e-6,
                    "coefficient {index}: |{after}| > |{before}|"
                );
            }
        }

        /// Schur fed a *real* autocorrelation sequence — the only thing its callers ever pass —
        /// must stay finite, keep every reflection coefficient inside the unit circle, and return a
        /// non-negative residual energy. The `+ R0 * 1e-3 + 1` noise floor is exactly what
        /// `silk_find_pitch_lags_FLP:88` adds before calling it, and it is what makes the
        /// positive-definiteness hold for a silent input too.
        ///
        /// Feeding an *arbitrary* vector instead would be testing a case that cannot occur: an
        /// indefinite "autocorrelation" makes the recursion diverge by construction, in the C as
        /// much as here.
        #[test]
        fn schur_on_a_real_autocorrelation_is_stable(
            signal in prop::collection::vec(-8000.0f32..8000.0, 64..=64),
        ) {
            let mut corr = [0.0f32; 9];
            autocorrelation(&mut corr, &signal);
            corr[0] += corr[0] * 1e-3 + 1.0;
            let mut reflection = [0.0f32; 8];
            let residual = schur(&mut reflection, &corr);
            prop_assert!(residual.is_finite() && residual >= 0.0, "residual {residual}");
            for value in reflection {
                prop_assert!(value.is_finite() && value.abs() < 1.0, "reflection {value}");
            }
        }
    }
