#!/usr/bin/env bash
# Regenerate crates/siphon-rtp-codec/src/evs/{cnst,rom}/ from the TS 26.442 headers and ROM sources.
#
# The ROM files are compiled with debug info into a throwaway binary, and rom_export.py (run inside
# gdb) reads every table back out with its exact type, so macros, casts, constant expressions and
# pointers into other tables are taken as the compiler resolved them rather than re-parsed.
set -euo pipefail

evs_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_dir="${evs_dir}/c-code"
out_dir="${evs_dir}/../../crates/siphon-rtp-codec/src/evs/rom"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

includes=(-I"${source_dir}/basic_op" -I"${source_dir}/basic_math" -I"${source_dir}/lib_com"
  -I"${source_dir}/lib_dec" -I"${source_dir}/lib_enc")
roms=(lib_com/rom_com_fx lib_dec/rom_dec_fx lib_com/rom_basop_util basic_math/rom_basic_math)
for rom in "${roms[@]}"; do
  gcc -c -g -O0 -fwrapv -w -DRELEASE "${includes[@]}" -o "${work}/$(basename "${rom}").o" "${source_dir}/${rom}.c"
done
for support in basop32 enh1632 control count; do
  gcc -c -g -O0 -fwrapv -w -DRELEASE "${includes[@]}" -o "${work}/${support}.o" "${source_dir}/basic_op/${support}.c"
done
# rom_com_fx.c tables reference TNS coder functions by address; stub them so the binary links.
{
  for symbol in $(nm -u "${work}/rom_com_fx.o" | awk '{print $2}'); do echo "void ${symbol}(void) {}"; done
  echo 'int main(void) { return 0; }'
} > "${work}/stubs.c"
gcc -c -g -O0 -w -o "${work}/stubs.o" "${work}/stubs.c"
gcc -g -O0 -o "${work}/romdump" "${work}"/*.o -lm

# Data symbols of the ROM objects only: name, address, size, object.
: > "${work}/symbols.txt"
for rom in "${roms[@]}"; do
  object="$(basename "${rom}")"
  nm -S --defined-only "${work}/${object}.o" | awk '$3 ~ /^[RDrd]$/ && $4 !~ /^__/ {print $4}' |
    while read -r name; do
      nm -S --defined-only "${work}/romdump" | awk -v n="${name}" -v obj="${object}" '$4 == n {print $4, $1, $2, obj}'
    done >> "${work}/symbols.txt"
done

python3 -I "${evs_dir}/oracle/gen_cnst.py" "${source_dir}" "${out_dir}/../cnst"
rm -rf "${out_dir}"
mkdir -p "${out_dir}"
# Constant names first, so a table never takes a name evs::cnst already uses.
grep -ho '^pub const [A-Za-z0-9_]*' "${out_dir}/../cnst/"*.rs | awk '{print $3}' > "${work}/reserved.txt"
ROM_RESERVED="${work}/reserved.txt" ROM_SYMBOLS="${work}/symbols.txt" ROM_OUT="${out_dir}" gdb -batch -nx -x "${evs_dir}/oracle/rom_export.py" "${work}/romdump"

{
  echo "//! The TS 26.442 ROM tables, generated by \`reference/evs/oracle/gen_rom.sh\`; do not edit."
  echo "//!"
  echo "//! Each table keeps the reference's name, upper-cased. A pointer in a reference table becomes a"
  echo "//! slice from the pointed-to element to the end of its target table; a null pointer becomes an"
  echo "//! empty slice. \`unsupported.txt\` beside this file lists the tables not exported (function"
  echo "//! pointers), which are ported by hand where they are used."
  echo
  echo "#![allow(clippy::unreadable_literal, clippy::excessive_precision, clippy::approx_constant)]"
  echo
  echo "/// \`&slice[start..]\`, usable in a static initializer."
  echo "pub const fn tail<T>(slice: &'static [T], start: usize) -> &'static [T] {"
  echo "    slice.split_at(start).1"
  echo "}"
  echo
  echo "pub mod types;"
  while read -r module; do
    [[ -n "${module}" ]] && echo "mod ${module};"
  done < "${out_dir}/modules.txt"
  echo
  while read -r module; do
    [[ -n "${module}" ]] && echo "pub use ${module}::*;"
  done < "${out_dir}/modules.txt"
  echo "pub use types::*;"
} > "${out_dir}/mod.rs"
rm -f "${out_dir}/modules.txt"
echo "wrote ${out_dir}"

# Same formatting cargo fmt would apply, so regenerating is byte-stable.
rustfmt --edition 2021 "${out_dir}"/*.rs "${out_dir}/../cnst/"*.rs
# rustfmt spreads struct entries over several lines; re-split so no file passes the size gate.
python3 -I "${evs_dir}/oracle/rom_split.py" "${out_dir}"
rustfmt --edition 2021 "${out_dir}"/*.rs
