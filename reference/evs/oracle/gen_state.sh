#!/usr/bin/env bash
# Regenerate crates/siphon-rtp-codec/src/evs/dec/state/ from the TS 26.442 decoder state struct.
#
# Like gen_rom.sh, the layout comes from the compiler's debug info (state_export.py, run in gdb), so
# every array bound is the evaluated macro. Pointer fields other than struct handles take the hand
# designs in state_export.py's DESIGNS table.
set -euo pipefail

evs_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_dir="${evs_dir}/c-code"
out_dir="${evs_dir}/../../crates/siphon-rtp-codec/src/evs/dec/state"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

includes=(-I"${source_dir}/basic_op" -I"${source_dir}/basic_math" -I"${source_dir}/lib_com"
  -I"${source_dir}/lib_dec" -I"${source_dir}/lib_enc")
gcc -c -g -O0 -w -DRELEASE "${includes[@]}" -o "${work}/init_dec.o" "${source_dir}/lib_dec/init_dec_fx.c"

# Field comments from the headers: `Type name[...];  /* comment */`, keyed by field name.
python3 -I - "${source_dir}" "${work}/comments.json" <<'PY'
import json, re, sys
source, out = sys.argv[1], sys.argv[2]
comments = {}
for header in ("lib_dec/stat_dec_fx.h", "lib_com/stat_com.h", "lib_com/cldfb.h", "lib_com/basop_util.h"):
    try:
        text = open(f"{source}/{header}", encoding="latin-1").read()
    except FileNotFoundError:
        continue
    for match in re.finditer(r"(\w+)\s*(?:\[[^;]*\])*\s*;\s*/\*\s*(.*?)\s*\*/", text):
        name, comment = match.group(1), " ".join(match.group(2).split())
        comment = comment.replace("`", "'")
        comments.setdefault(name, comment)
json.dump(comments, open(out, "w"))
PY

# Struct types the ROM tables define; the state shares them (state_export.py SHARED_TYPES).
grep -o '^pub struct [A-Za-z0-9_]*' "${out_dir}/../../rom/types.rs" | awk '{print $3}' > "${work}/rom_types.txt"
rm -rf "${out_dir}"
mkdir -p "${out_dir}"
STATE_ROM_TYPES="${work}/rom_types.txt" STATE_OUT="${out_dir}" STATE_ROOT=Decoder_State_fx STATE_COMMENTS="${work}/comments.json" \
  gdb -batch -nx -ex "set max-value-size unlimited" -x "${evs_dir}/oracle/state_export.py" "${work}/init_dec.o"

{
  echo "//! The decoder state, generated by \`reference/evs/oracle/gen_state.sh\` from the reference's"
  echo "//! \`Decoder_State_fx\` and every struct it reaches. Field names are the reference's, snake-cased,"
  echo "//! with \`_fx\` dropped; each field's doc comment gives the C name, so a port can be read side by"
  echo "//! side with TS 26.442."
  echo
  echo "#![allow(clippy::struct_field_names, clippy::large_stack_arrays)]"
  echo
  echo "pub use crate::evs::rom::types::*;"
  echo
  while read -r module; do [[ -n "${module}" ]] && echo "mod ${module};"; done < "${out_dir}/modules.txt"
  echo
  while read -r module; do
    [[ -n "${module}" && "${module}" != *_zeroed ]] && echo "pub use ${module}::*;"
  done < "${out_dir}/modules.txt"
} > "${out_dir}/mod.rs"
rm -f "${out_dir}/modules.txt"
echo "wrote ${out_dir}"

# Same formatting cargo fmt would apply, so regenerating is byte-stable.
rustfmt --edition 2021 "${out_dir}"/*.rs 